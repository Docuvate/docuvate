import { useEffect, useRef } from 'react';

/** Focus the returned ref once when the host mounts (replaces `autoFocus`). */
export function useAutofocusOnMount<T extends HTMLElement>() {
  const ref = useRef<T>(null);
  useEffect(() => {
    ref.current?.focus();
  }, []);
  return ref;
}
