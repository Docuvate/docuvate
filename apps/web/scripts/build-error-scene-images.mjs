import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(__dirname, '..');
const sourceDir = path.join(webRoot, 'assets', 'error-scenes-source');
const outDir = path.join(webRoot, 'public', 'error-scenes');
const manifestPath = path.join(webRoot, 'src', 'components', 'errors', 'errorSceneManifest.generated.ts');

const WIDTHS = [480, 960, 1440];
const LIGHT_KEY = { r: 245, g: 241, b: 233 };
const DARK_BG = { r: 30, g: 26, b: 19 };
const KEY_THRESHOLD = 42;

const SCENES = [
  { id: 'unexpected', file: 'mascot-base.jpg', slug: 'mascot-base' },
  { id: 'unreachable', file: 'unreachable.jpg', slug: 'unreachable' },
  { id: 'offline', file: 'offline.jpg', slug: 'offline' },
  { id: 'notFound', file: 'not-found.jpg', slug: 'not-found' },
  { id: 'serverFault', file: 'server-error.jpg', slug: 'server-error' },
  { id: 'forbidden', file: 'forbidden.jpg', slug: 'forbidden' },
];

function colorDistance(r, g, b, key) {
  return Math.sqrt((r - key.r) ** 2 + (g - key.g) ** 2 + (b - key.b) ** 2);
}

async function replaceBackdropWithDark(inputBuffer) {
  const { data, info } = await sharp(inputBuffer).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const pixels = new Uint8Array(data);
  for (let i = 0; i < info.width * info.height; i += 1) {
    const offset = i * 4;
    const r = pixels[offset];
    const g = pixels[offset + 1];
    const b = pixels[offset + 2];
    if (colorDistance(r, g, b, LIGHT_KEY) <= KEY_THRESHOLD) {
      pixels[offset] = DARK_BG.r;
      pixels[offset + 1] = DARK_BG.g;
      pixels[offset + 2] = DARK_BG.b;
      pixels[offset + 3] = 255;
    }
  }
  return sharp(pixels, {
    raw: { width: info.width, height: info.height, channels: 4 },
  }).png();
}

async function encodeVariant(pipeline, outPath, format) {
  if (format === 'webp') {
    await pipeline.clone().webp({ quality: 76, effort: 5 }).toFile(outPath);
    return;
  }
  await pipeline.clone().avif({ quality: 48, effort: 5 }).toFile(outPath);
}

async function buildScene(scene) {
  const sourcePath = path.join(sourceDir, scene.file);
  const meta = await sharp(sourcePath).metadata();
  if (meta.width == null || meta.height == null) {
    throw new Error(`Missing dimensions for ${scene.file}`);
  }
  const aspect = meta.height / meta.width;
  const sceneDir = path.join(outDir, scene.slug);
  await mkdir(sceneDir, { recursive: true });

  const entry = {
    id: scene.id,
    slug: scene.slug,
    width: meta.width,
    height: meta.height,
  };

  for (const width of WIDTHS) {
    const height = Math.round(width * aspect);
    const lightPipeline = sharp(sourcePath).resize(width, height, { fit: 'inside', withoutEnlargement: false });
    const darkBase = await replaceBackdropWithDark(await sharp(sourcePath).resize(width, height).toBuffer());
    const darkPipeline = darkBase;

    for (const theme of ['light', 'dark']) {
      const pipeline = theme === 'light' ? lightPipeline : darkPipeline;
      const suffix = theme === 'light' ? '' : '-dark';
      const webpPath = path.join(sceneDir, `${scene.slug}-${width}${suffix}.webp`);
      const avifPath = path.join(sceneDir, `${scene.slug}-${width}${suffix}.avif`);
      await encodeVariant(pipeline, webpPath, 'webp');
      await encodeVariant(pipeline, avifPath, 'avif');
    }
  }

  return entry;
}

function renderManifest(entries) {
  const lines = [
    '// SPDX-FileCopyrightText: 2026 Thomas Faust',
    '// SPDX-License-Identifier: LicenseRef-Docuvate-SUL-1.0',
    '// Generated by scripts/build-error-scene-images.mjs — do not edit.',
    '',
    'export type ErrorSceneId =',
    "  | 'offline'",
    "  | 'unreachable'",
    "  | 'serverFault'",
    "  | 'notFound'",
    "  | 'unexpected'",
    "  | 'forbidden';",
    '',
    'export type ErrorSceneThemeVariant = "light" | "dark";',
    '',
    'export interface ErrorSceneManifestEntry {',
    '  id: ErrorSceneId;',
    '  slug: string;',
    '  width: number;',
    '  height: number;',
    '}',
    '',
    'export const ERROR_SCENE_WIDTHS: readonly number[] = [480, 960, 1440];',
    '',
    'export const ERROR_SCENE_MANIFEST: Record<ErrorSceneId, ErrorSceneManifestEntry> = {',
  ];

  for (const entry of entries) {
    lines.push(
      `  ${entry.id}: { id: '${entry.id}', slug: '${entry.slug}', width: ${entry.width}, height: ${entry.height} },`
    );
  }
  lines.push('};', '');
  return lines.join('\n');
}

async function main() {
  await mkdir(outDir, { recursive: true });
  const entries = [];
  for (const scene of SCENES) {
    entries.push(await buildScene(scene));
  }
  await writeFile(manifestPath, renderManifest(entries), 'utf8');
  const { execSync } = await import('node:child_process');
  const du = execSync(`du -sb ${outDir}`, { encoding: 'utf8' }).trim().split('\t')[0];
  const bytes = Number(du);
  if (bytes > 1_600_000) {
    console.warn(`warning: error-scenes assets are ${bytes} bytes (> 1.5 MB target)`);
  }
  console.log(`Built error scene assets (${bytes} bytes) -> ${outDir}`);
}

await main();
