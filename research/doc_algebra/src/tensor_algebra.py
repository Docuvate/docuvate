"""
Truncated tensor algebra D_3 = R ⊕ V ⊕ V⊗2 ⊕ V⊗3, deg > 3 discarded.

Product: (A * B)_k = sum_{j=0}^{k} A_j ⊗ B_{k-j} for k=0,1,2,3 (tensor product
over R, then truncate). Associative because it is the quotient of the free
associative algebra by the ideal generated by degrees > 3.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np


def _tp(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    return np.kron(a, b)


@dataclass
class TruncatedTensor:
    """Components g0 (scalar), g1 (d,), g2 (d^2,), g3 (d^3,) flattened."""

    g0: float
    g1: np.ndarray
    g2: np.ndarray
    g3: np.ndarray

    @classmethod
    def from_vector(cls, v: np.ndarray, d: int) -> TruncatedTensor:
        v = np.asarray(v, dtype=np.float64).ravel()
        i0 = 1
        i1 = i0 + d
        i2 = i1 + d * d
        i3 = i2 + d * d * d
        return cls(
            g0=float(v[0]),
            g1=v[i0:i1].copy(),
            g2=v[i1:i2].copy(),
            g3=v[i2:i3].copy(),
        )

    def to_vector(self, d: int) -> np.ndarray:
        return np.concatenate([[self.g0], self.g1, self.g2, self.g3])

    @property
    def dim(self, d: int = 2) -> int:
        return 1 + d + d**2 + d**3


def zero(d: int) -> TruncatedTensor:
    return TruncatedTensor(0.0, np.zeros(d), np.zeros(d * d), np.zeros(d * d * d))


def mul_trunc(a: TruncatedTensor, b: TruncatedTensor, d: int) -> TruncatedTensor:
    """Truncated tensor product in D_3."""
    g0 = a.g0 * b.g0
    g1 = a.g0 * b.g1 + a.g1 * b.g0
    g2 = a.g0 * b.g2 + np.outer(a.g1, b.g1).ravel() + a.g2 * b.g0
    g3 = (
        a.g0 * b.g3
        + a.g3 * b.g0
        + np.kron(a.g1, b.g2)
        + np.kron(a.g2, b.g1)
    )
    return TruncatedTensor(g0, g1, g2, g3)


def geometric_vectors_d2() -> int:
    return 2


def feature_dim(d: int) -> int:
    return 1 + d + d**2 + d**3


def encode_position(x: float, y: float, d: int = 2) -> TruncatedTensor:
    g1 = np.zeros(d)
    g1[0] = x
    if d > 1:
        g1[1] = y
    return TruncatedTensor(1.0, g1, np.zeros(d * d), np.zeros(d * d * d))


def grade_slices(d: int) -> dict[str, slice]:
    i0 = 0
    i1 = 1
    i2 = i1 + d
    i3 = i2 + d * d
    i4 = i3 + d * d * d
    return {
        "g0": slice(i0, i1),
        "g1": slice(i1, i2),
        "g2": slice(i2, i3),
        "g3": slice(i3, i4),
    }


def compressed_projection(vec: np.ndarray, d: int, keep_grades: tuple[int, ...]) -> np.ndarray:
    """Keep only selected grades (0..3); arbitrary linear projection may break associativity."""
    sl = grade_slices(d)
    out = np.zeros_like(vec)
    for g in keep_grades:
        key = f"g{g}"
        if key in sl:
            out[sl[key]] = vec[sl[key]]
    return out
