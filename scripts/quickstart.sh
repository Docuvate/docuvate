set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

MIN_HOST_RAM_MIB="${DOCUVATE_QUICKSTART_MIN_RAM_MIB:-6144}"
WEB_URL="${DOCUVATE_QUICKSTART_WEB_URL:-http://localhost:5173}"
API_READY_URL="${DOCUVATE_QUICKSTART_API_READY_URL:-http://localhost:3001/health/ready}"
COMPOSE_FILES=(-f docker-compose.yml)

if [[ -f docker-compose.dev.yml ]] && [[ "${DOCUVATE_QUICKSTART_BUILD:-0}" == "1" ]]; then
  COMPOSE_FILES+=(-f docker-compose.dev.yml)
fi

die() {
  echo "quickstart: $*" >&2
  exit 1
}

if ! command -v docker >/dev/null 2>&1; then
  die "Docker is not installed. Install Docker Engine or Docker Desktop first."
fi

if ! docker info >/dev/null 2>&1; then
  die "Docker daemon is not running. Start Docker and retry."
fi

if ! docker compose version >/dev/null 2>&1; then
  die "docker compose v2 is required (docker compose version)."
fi

host_ram_mib=0
if command -v free >/dev/null 2>&1; then
  host_ram_mib="$(free -m | awk '/^Mem:/ {print $2}')"
elif [[ "$(uname -s)" == "Darwin" ]] && command -v sysctl >/dev/null 2>&1; then
  host_ram_mib="$(sysctl -n hw.memsize | awk '{print int($1/1024/1024)}')"
fi

if [[ "$host_ram_mib" -gt 0 && "$host_ram_mib" -lt "$MIN_HOST_RAM_MIB" ]]; then
  die "Host RAM is ${host_ram_mib} MiB; Docuvate Compose needs at least ${MIN_HOST_RAM_MIB} MiB (see README#quickstart)."
fi

gen_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 48 | tr -d '/+=' | head -c 48
  else
    dd if=/dev/urandom bs=32 count=1 2>/dev/null | base64 | tr -d '/+=' | head -c 48
  fi
}

if [[ ! -f .env ]]; then
  echo "== Writing .env from .env.example with generated secrets =="
  cp .env.example .env
  {
    echo ""
    echo "# Generated by scripts/quickstart.sh on $(date -u +%Y-%m-%dT%H:%MZ)"
    echo "BETTER_AUTH_SECRET=$(gen_secret)"
    if ! grep -q '^DOCUVATE_CONNECTOR_SECRETS_KEY=' .env || grep -q 'dev-change-me' .env; then
      echo "DOCUVATE_CONNECTOR_SECRETS_KEY=$(gen_secret)!!"
    fi
  } >> .env
else
  echo "== Using existing .env =="
  if ! grep -q '^BETTER_AUTH_SECRET=.\{32,\}' .env; then
    die "Set BETTER_AUTH_SECRET in .env (at least 32 characters) or remove .env to regenerate."
  fi
fi

echo "== Pulling application images (api, web, worker) =="
docker compose "${COMPOSE_FILES[@]}" pull api web worker migrate 2>/dev/null || true

UP_ARGS=(up -d)
if [[ "${DOCUVATE_QUICKSTART_BUILD:-0}" == "1" ]]; then
  UP_ARGS+=(--build)
fi

echo "== Starting stack =="
docker compose "${COMPOSE_FILES[@]}" "${UP_ARGS[@]}"

wait_http_ready() {
  local url="$1"
  local label="$2"
  local attempts="${3:-120}"
  local i=1
  while [[ "$i" -le "$attempts" ]]; do
    if curl -fsS "$url" >/dev/null 2>&1; then
      echo "  $label: ready"
      return 0
    fi
    sleep 2
    i=$((i + 1))
  done
  die "$label did not become ready (${url}). Run: docker compose logs api worker web"
}

echo "== Waiting for health =="
wait_http_ready "http://localhost:3001/health" "API liveness" 90
wait_http_ready "$API_READY_URL" "API readiness" 120
wait_http_ready "$WEB_URL" "Web" 90

cat <<EOF

Docuvate is up.

  Web:     $WEB_URL
  API:     http://localhost:3001/health/ready
  Mailpit: http://localhost:8025 (password reset mail in local dev)

First login:
  1. Open the web URL and register the first account (becomes installation admin).
  2. Upload PDFs or images under Library.
  3. Open a document for OCR text, labels, and chat (extractive by default; optional local LLM: see README#quickstart).

Diagnostics: bash scripts/doctor.sh
Upgrade/backup: docs/self-hosting.md

EOF
