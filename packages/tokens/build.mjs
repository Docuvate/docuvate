import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

import {
  THEME_ATTR,
  camelName,
  colorRoles,
  cssVarName,
  loadStaticTokens,
  readColorJson,
  tokensDir,
} from './lib.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distCss = path.join(__dirname, 'dist/css');
const distJs = path.join(__dirname, 'dist/js');
const distDart = path.join(__dirname, 'dist/dart');

const HEADER = 'Generated by @docuvate/tokens from packages/tokens/tokens/*.json — do not edit';

function tokenPathToDartField(pathParts) {
  return pathParts.map((p) => p.replace(/-([a-z])/g, (_, c) => c.toUpperCase())).join('');
}

function assertUnique(items, key, label) {
  const seen = new Map();
  for (const item of items) {
    const k = item[key];
    if (seen.has(k)) {
      throw new Error(`Duplicate ${label} "${k}" (${seen.get(k)} and ${item.id ?? item.role})`);
    }
    seen.set(k, item.id ?? item.role);
  }
}

function buildThemedCss(roles) {
  const lines = [`/** ${HEADER} */`, '', `:root, [${THEME_ATTR}='light'] {`];
  for (const r of roles) lines.push(`  ${r.cssVar}: ${r.light};`);
  lines.push('}', '', `[${THEME_ATTR}='dark'] {`);
  for (const r of roles) lines.push(`  ${r.cssVar}: ${r.dark};`);
  lines.push('}', '');
  return lines.join('\n');
}

function buildStaticCss(tokens) {
  const lines = [':root {'];
  let file = '';
  for (const t of tokens) {
    if (t.file !== file) {
      file = t.file;
      lines.push(`  /* ${file} */`);
    }
    lines.push(`  ${t.cssVar}: ${t.cssValue};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const REDUCED_MOTION_CSS = `@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}
`;

function buildTs(tokens, roles) {
  const lines = [
    `/** ${HEADER} */`,
    '',
    'export const docuvateThemeAttribute = "data-docuvate-theme";',
    '',
    'export const tokens = {',
  ];
  for (const t of tokens) lines.push(`  ${t.camel}: ${JSON.stringify(t.resolved)},`);
  for (const theme of ['light', 'dark']) {
    lines.push(`  color${theme.charAt(0).toUpperCase() + theme.slice(1)}: {`);
    for (const r of roles) lines.push(`    ${camelName(['color', r.role])}: ${JSON.stringify(r[theme])},`);
    lines.push('  },');
  }
  lines.push('};', '');
  lines.push('export const labelDefaultColor = tokens.colorLight.colorLabelDefault;', '');
  const catalog = tokens.map((t) => ({
    id: t.id,
    group: t.path[0],
    cssVar: t.cssVar,
    value: t.value,
    resolved: t.resolved,
    aliasOf: t.aliasOf,
    comment: t.comment,
  }));
  lines.push(`export const tokenCatalog = ${JSON.stringify(catalog, null, 2)};`, '');
  lines.push(`export const colorCatalog = ${JSON.stringify(roles, null, 2)};`, '');
  return lines.join('\n');
}

function buildTsDecl(tokens, roles) {
  const lines = [
    `/** ${HEADER} */`,
    '',
    'export declare const docuvateThemeAttribute: "data-docuvate-theme";',
    'export type DocuvateTheme = "light" | "dark";',
    '',
    'type ThemeColors = {',
  ];
  for (const r of roles) lines.push(`  ${camelName(['color', r.role])}: string;`);
  lines.push('};', '', 'export declare const tokens: {');
  for (const t of tokens) lines.push(`  ${t.camel}: string;`);
  lines.push('  colorLight: ThemeColors;', '  colorDark: ThemeColors;', '};', '');
  lines.push('export declare const labelDefaultColor: string;', '');
  lines.push(
    'export interface TokenCatalogEntry {',
    '  readonly id: string;',
    '  readonly group: string;',
    '  readonly cssVar: string;',
    '  readonly value: string;',
    '  readonly resolved: string;',
    '  readonly aliasOf: string | null;',
    '  readonly comment: string;',
    '}',
    '',
    'export interface ColorCatalogEntry {',
    '  readonly role: string;',
    '  readonly cssVar: string;',
    '  readonly light: string;',
    '  readonly dark: string | null;',
    '}',
    '',
    'export declare const tokenCatalog: readonly TokenCatalogEntry[];',
    'export declare const colorCatalog: readonly ColorCatalogEntry[];',
    ''
  );
  return lines.join('\n');
}

function hexToFlutterColor(hex) {
  const h = hex.replace('#', '');
  if (h.length === 6) return `Color(0xFF${h.toUpperCase()})`;
  return `Color(0xFF000000)`;
}

function buildDart(tokens, roles) {
  const lines = [
    `// ${HEADER}`,
    "import 'dart:ui' show Color;",
    '',
    'enum DocuvateThemeId { light, dark }',
    '',
    'class DocuvateTokens {',
    '  DocuvateTokens._();',
    '',
  ];
  for (const t of tokens) {
    const name = tokenPathToDartField(t.path);
    const v = t.resolved;
    if (/^-?[\d.]+px$/.test(v)) lines.push(`  static const double ${name} = ${parseFloat(v)};`);
    else if (/^-?[\d.]+rem$/.test(v)) lines.push(`  static const double ${name} = ${parseFloat(v)} * 16;`);
    else lines.push(`  static const String ${name} = ${JSON.stringify(v)};`);
  }
  lines.push(
    '',
    '  static Color color(DocuvateThemeId theme, String role) {',
    '    switch (theme) {',
    '      case DocuvateThemeId.light:',
    '        return _lightColor(role);',
    '      case DocuvateThemeId.dark:',
    '        return _darkColor(role);',
    '    }',
    '  }',
    ''
  );
  for (const theme of ['light', 'dark']) {
    lines.push(`  static Color _${theme}Color(String role) {`, '    switch (role) {');
    for (const r of roles) {
      lines.push(`      case '${r.role}':`, `        return ${hexToFlutterColor(r[theme])};`);
    }
    lines.push('      default:', '        return const Color(0xFF000000);', '    }', '  }', '');
  }
  lines.push(
    '}',
    '',
    'extension DocuvateThemeData on DocuvateThemeId {',
    "  Color bg() => DocuvateTokens.color(this, 'bg');",
    "  Color accent() => DocuvateTokens.color(this, 'accent');",
    '}',
    ''
  );
  return lines.join('\n');
}

/** Style Dictionary pass validates token JSON shape and alias references. */
async function runStyleDictionaryValidate() {
  const sd = new StyleDictionary({
    log: { verbosity: 'silent' },
    source: [path.join(tokensDir, '**/*.json')],
    platforms: {
      json: {
        transformGroup: 'js',
        buildPath: path.join(__dirname, '.sd-cache/'),
        files: [{ destination: 'tokens.raw.json', format: 'json/nested' }],
      },
    },
  });
  await sd.buildAllPlatforms();
}

fs.mkdirSync(distCss, { recursive: true });
fs.mkdirSync(distJs, { recursive: true });
fs.mkdirSync(distDart, { recursive: true });

await runStyleDictionaryValidate();

const tokens = loadStaticTokens();
const roles = colorRoles(readColorJson());
assertUnique(tokens, 'cssVar', 'CSS variable');
assertUnique(tokens, 'camel', 'TS key');
assertUnique(roles, 'cssVar', 'colour variable');
for (const r of roles) {
  if (r.dark == null) throw new Error(`Colour role "${r.role}" has no dark value (light/dark parity)`);
  if (tokens.some((t) => t.cssVar === r.cssVar)) throw new Error(`Static token shadows colour ${r.cssVar}`);
}

fs.writeFileSync(
  path.join(distCss, 'tokens.css'),
  buildThemedCss(roles) + buildStaticCss(tokens) + REDUCED_MOTION_CSS
);
fs.writeFileSync(path.join(distJs, 'tokens.js'), buildTs(tokens, roles));
fs.writeFileSync(path.join(distJs, 'tokens.d.ts'), buildTsDecl(tokens, roles));
fs.writeFileSync(path.join(distDart, 'docuvate_tokens.dart'), buildDart(tokens, roles));

console.log(`Built @docuvate/tokens (${String(tokens.length)} static tokens, ${String(roles.length)} colour roles)`);
